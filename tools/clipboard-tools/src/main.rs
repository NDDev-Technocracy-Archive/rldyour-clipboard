use nddev_clipboard_api::{content, desktop, wire};
use serde_json::json;
use std::path::Path;
use utoipa::OpenApi;

#[derive(OpenApi)]
#[openapi(components(schemas(
    wire::Request,
    wire::Response,
    wire::Summary,
    wire::Role,
    desktop::View,
    desktop::DesktopAction,
    desktop::DesktopEntry,
    desktop::DesktopResult
)))]
struct LocalContract;

#[path = "../fingerprint.rs"]
mod fingerprint;

fn main() -> std::process::ExitCode {
    let result = run();
    match result {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("clipboard-tools: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let command = std::env::args()
        .nth(1)
        .ok_or("expected check or generate")?;
    let root = std::env::current_dir()?.canonicalize()?;
    let manifest: toml::Value = toml::from_str(&std::fs::read_to_string(root.join("Cargo.toml"))?)?;
    let package = &manifest["workspace"]["package"];
    if package["repository"].as_str() != Some(env!("CARGO_PKG_REPOSITORY")) {
        return Err("run the tool from the NDDev Clipboard source root".into());
    }
    if fingerprint::fingerprint(&root)? != env!("CLIPBOARD_TOOLS_INPUTS") {
        return Err("tool inputs changed; prepare clipboard-tools from these sources".into());
    }
    match command.as_str() {
        "check" => generated(&root, false),
        "generate" => generated(&root, true),
        "install-tool" => {
            let directory = root.join(".tools/bin");
            std::fs::create_dir_all(&directory)?;
            let target = directory.join(format!("clipboard-tools{}", std::env::consts::EXE_SUFFIX));
            std::fs::copy(std::env::current_exe()?, target)?;
            Ok(())
        }
        _ => Err("expected check or generate".into()),
    }
}

fn generated(root: &Path, write: bool) -> Result<(), Box<dyn std::error::Error>> {
    let schema = serde_json::to_string_pretty(&nddev_clipboard_api::config_schema())? + "\n";
    output(root, "contracts/config.schema.json", &schema, write)?;
    let mut api = serde_json::to_value(LocalContract::openapi())?;
    api["info"]["title"] = json!("NDDev Clipboard local IPC");
    api["x-transport"] = json!({
        "framing": "UTF-8 JSON object and LF; declared payload bytes follow immediately",
        "protocol_version": wire::PROTOCOL_VERSION,
        "max_control_frame_bytes": wire::MAX_FRAME,
        "http_endpoints": false
    });
    output(
        root,
        "contracts/local-ipc.openapi.json",
        &(serde_json::to_string_pretty(&api)? + "\n"),
        write,
    )?;
    let rank: serde_json::Map<String, serde_json::Value> = content::MIME_RANKS
        .iter()
        .map(|(name, value)| ((*name).to_owned(), json!(value)))
        .collect();
    let mut javascript =
        String::from("// Generated by clipboard-tools from the Rust product contract.\n");
    for (name, value) in [
        ("PROTOCOL_VERSION", json!(wire::PROTOCOL_VERSION)),
        ("MAX_FRAME", json!(wire::MAX_FRAME)),
        ("MAX_REPRESENTATIONS", json!(content::MAX_REPRESENTATIONS)),
        ("SENSITIVE", json!(content::SENSITIVE)),
        ("PROTOCOL_TARGETS", json!(content::PROTOCOL_TARGETS)),
        ("RANK", json!(rank)),
    ] {
        javascript.push_str(&format!(
            "export const {name} = {};\n",
            serde_json::to_string(&value)?
        ));
    }
    output(root, "extension/lib/contract.js", &javascript, write)?;
    output(
        root,
        "python/src/rldyour_clipboard/_contract.py",
        &format!(
            "# Generated by clipboard-tools from the Rust product contract.\n__version__ = \"{}\"\nPROTOCOL_VERSION = {}\nMAX_FRAME = {}\n",
            env!("CARGO_PKG_VERSION"),
            wire::PROTOCOL_VERSION,
            wire::MAX_FRAME
        ),
        write,
    )?;
    output(
        root,
        "macos/GeneratedContract.swift",
        &format!(
            "// Generated by clipboard-tools from the Rust product contract.\nenum ClipboardContract {{\n    static let protocolVersion = {}\n    static let maxFrame = {}\n}}\n",
            wire::PROTOCOL_VERSION,
            wire::MAX_FRAME
        ),
        write,
    )?;
    let path = root.join("extension/metadata.json");
    let mut metadata: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(path)?)?;
    let version = env!("CARGO_PKG_VERSION");
    let parts: Vec<u64> = version
        .split('.')
        .map(str::parse)
        .collect::<Result<_, _>>()?;
    if parts.len() != 3 || parts.iter().any(|value| *value >= 1000) {
        return Err("extension version requires three numbers below 1000".into());
    }
    metadata["version-name"] = json!(version);
    metadata["version"] = json!(parts[0] * 1_000_000 + parts[1] * 1000 + parts[2]);
    output(
        root,
        "extension/metadata.json",
        &(serde_json::to_string_pretty(&metadata)? + "\n"),
        write,
    )?;
    let mut package: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(
        root.join("ui/package.template.json"),
    )?)?;
    package["version"] = json!(version);
    output(
        root,
        "ui/package.json",
        &(serde_json::to_string_pretty(&package)? + "\n"),
        write,
    )?;
    println!("generated contracts are current ({version})");
    Ok(())
}

fn output(
    root: &Path,
    name: &str,
    text: &str,
    write: bool,
) -> Result<(), Box<dyn std::error::Error>> {
    let path = root.join(name);
    if write {
        std::fs::create_dir_all(path.parent().ok_or("schema has no parent")?)?;
        std::fs::write(&path, text)?;
    } else if std::fs::read_to_string(&path)? != text {
        return Err(format!("{name} differs; run clipboard-tools generate").into());
    }
    Ok(())
}
