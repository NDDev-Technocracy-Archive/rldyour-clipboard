use serde::{Deserialize, Serialize};
use std::fs::{File, OpenOptions};
use std::io::Read;
use std::path::{Component, Path, PathBuf};

const MAX_CONFIG_BYTES: u64 = 16 * 1024;
const MAX_RETENTION_DAYS: u32 = 36_500;
const SCHEMA: u8 = 1;

/// Configuration refusal. Errors contain no file contents or configured paths.
#[derive(Debug, thiserror::Error)]
pub enum ConfigError {
    #[error("configuration file could not be read ({0:?})")]
    Io(std::io::ErrorKind),
    #[error("configuration must be a regular file, not a redirect")]
    FileType,
    #[error("configuration exceeds its size limit")]
    TooLarge,
    #[error("configuration is not a supported TOML document")]
    Format,
    #[error("configuration schema is unsupported")]
    Schema,
    #[error("archive directory must be an absolute local path without parent components")]
    Archive,
    #[error("socket must be an absolute local path within the native address bound")]
    Socket,
    #[error("budget is outside the supported byte range")]
    Budget,
    #[error("retention is outside the supported day range")]
    Retention,
    #[error("the platform's configuration directory is unavailable")]
    Location,
}

impl From<std::io::Error> for ConfigError {
    fn from(error: std::io::Error) -> Self {
        Self::Io(error.kind())
    }
}

// One declaration supplies the serde model and its generated JSON Schema.
macro_rules! config_model {
    ($( $(#[$doc:meta])* $field:ident: $ty:ty => $schema:expr ),+ $(,)?) => {
        /// Complete file settings. Every value is explicit; there are no runtime defaults.
        #[derive(Clone, Deserialize, Serialize)]
        #[serde(deny_unknown_fields)]
        pub struct FileConfig {
            $( $(#[$doc])* pub $field: $ty, )+
        }

        /// JSON Schema for the same file model, generated by clipboard-tools.
        pub fn config_schema() -> serde_json::Value {
            serde_json::json!({
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$id": "https://nddev.ai/schemas/clipboard/config/1",
                "title": "NDDev Clipboard configuration",
                "type": "object",
                "additionalProperties": false,
                "required": [$(stringify!($field)),+],
                "properties": {$((stringify!($field)): $schema),+}
            })
        }
    }
}

config_model! {
    /// File model identity, independent of the local IPC version.
    schema: u8 => serde_json::json!({"type": "integer", "const": SCHEMA}),
    /// Archive path. Changing placement does not move or copy existing data.
    archive_dir: PathBuf => serde_json::json!({"type": "string", "minLength": 1}),
    /// Private AF_UNIX endpoint. TCP addresses are not supported.
    socket_path: PathBuf => serde_json::json!({"type": "string", "minLength": 1}),
    /// Bytes available to unpinned capture. Zero disables budget eviction.
    budget_bytes: u64 => serde_json::json!({"type": "integer", "minimum": 0, "maximum": i64::MAX}),
    /// Days since capture. Zero disables age expiry; pinning never resets age.
    retention_days: u32 => serde_json::json!({"type": "integer", "minimum": 0, "maximum": MAX_RETENTION_DAYS}),
    /// Whether this daemon may start its native clipboard watcher.
    capture_native: bool => serde_json::json!({"type": "boolean"}),
}

/// Validated immutable settings captured for one daemon/client lifetime.
#[derive(Clone)]
pub struct Config(FileConfig);

impl Config {
    /// Validate an explicit file model without contacting storage or a daemon.
    pub fn new(file: FileConfig) -> Result<Self, ConfigError> {
        if file.schema != SCHEMA {
            return Err(ConfigError::Schema);
        }
        if !local_path(&file.archive_dir) {
            return Err(ConfigError::Archive);
        }
        #[cfg(target_os = "macos")]
        let max_socket_bytes = 103;
        #[cfg(not(target_os = "macos"))]
        let max_socket_bytes = 107;
        if !local_path(&file.socket_path)
            || file.socket_path.as_os_str().as_encoded_bytes().len() > max_socket_bytes
            || file.socket_path.file_name().is_none()
        {
            return Err(ConfigError::Socket);
        }
        if file.budget_bytes > i64::MAX as u64 {
            return Err(ConfigError::Budget);
        }
        if file.retention_days > MAX_RETENTION_DAYS {
            return Err(ConfigError::Retention);
        }
        Ok(Self(file))
    }

    /// Read one bounded, regular, non-redirected configuration file.
    pub fn read(path: &Path) -> Result<Self, ConfigError> {
        if !local_path(path) {
            return Err(ConfigError::Location);
        }
        let mut file = open_config(path)?;
        let metadata = file.metadata()?;
        if !metadata.is_file() {
            return Err(ConfigError::FileType);
        }
        if metadata.len() > MAX_CONFIG_BYTES {
            return Err(ConfigError::TooLarge);
        }
        let mut bytes = Vec::new();
        file.by_ref()
            .take(MAX_CONFIG_BYTES + 1)
            .read_to_end(&mut bytes)?;
        if bytes.len() as u64 > MAX_CONFIG_BYTES {
            return Err(ConfigError::TooLarge);
        }
        let text = std::str::from_utf8(&bytes).map_err(|_| ConfigError::Format)?;
        Self::parse(text)
    }

    /// Parse complete TOML settings. Errors never include the source document.
    pub fn parse(text: &str) -> Result<Self, ConfigError> {
        if text.len() as u64 > MAX_CONFIG_BYTES {
            return Err(ConfigError::TooLarge);
        }
        let file = toml::from_str(text).map_err(|_| ConfigError::Format)?;
        Self::new(file)
    }

    pub fn archive_dir(&self) -> &Path {
        &self.0.archive_dir
    }

    pub fn socket_path(&self) -> &Path {
        &self.0.socket_path
    }

    pub fn budget_bytes(&self) -> i64 {
        if self.0.budget_bytes == 0 {
            i64::MAX
        } else {
            self.0.budget_bytes as i64
        }
    }

    pub fn retention_seconds(&self) -> Option<i64> {
        (self.0.retention_days != 0).then_some(i64::from(self.0.retention_days) * 86_400)
    }

    pub fn capture_native(&self) -> bool {
        self.0.capture_native
    }

    pub fn to_toml(&self) -> Result<String, ConfigError> {
        toml::to_string_pretty(&self.0).map_err(|_| ConfigError::Format)
    }
}

fn local_path(path: &Path) -> bool {
    #[cfg(windows)]
    if !matches!(
        path.components().next(),
        Some(Component::Prefix(prefix))
            if matches!(prefix.kind(), std::path::Prefix::Disk(_) | std::path::Prefix::VerbatimDisk(_))
    ) {
        return false;
    }
    path.is_absolute()
        && !path
            .components()
            .any(|part| matches!(part, Component::ParentDir))
        && !path
            .as_os_str()
            .as_encoded_bytes()
            .iter()
            .any(u8::is_ascii_control)
}

fn open_config(path: &Path) -> Result<File, ConfigError> {
    let mut options = OpenOptions::new();
    options.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::OpenOptionsExt;
        use windows_sys::Win32::Storage::FileSystem::FILE_FLAG_OPEN_REPARSE_POINT;
        options.custom_flags(FILE_FLAG_OPEN_REPARSE_POINT);
    }
    let file = options.open(path)?;
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        use windows_sys::Win32::Storage::FileSystem::FILE_ATTRIBUTE_REPARSE_POINT;
        if file.metadata()?.file_attributes() & FILE_ATTRIBUTE_REPARSE_POINT != 0 {
            return Err(ConfigError::FileType);
        }
    }
    Ok(file)
}

/// The platform convention locates the file; it does not supply application settings.
pub fn default_config_path() -> Result<PathBuf, ConfigError> {
    #[cfg(target_os = "linux")]
    let root = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".config")));
    #[cfg(target_os = "macos")]
    let root = std::env::var_os("HOME")
        .map(|home| PathBuf::from(home).join("Library/Application Support"));
    #[cfg(windows)]
    let root = std::env::var_os("APPDATA").map(PathBuf::from);
    #[cfg(not(any(target_os = "linux", target_os = "macos", windows)))]
    let root: Option<PathBuf> = None;
    let root = root.ok_or(ConfigError::Location)?;
    if !root.is_absolute() {
        return Err(ConfigError::Location);
    }
    Ok(root.join("nddev").join("clipboard.toml"))
}

/// Placement used by explicit profile initialization, never as runtime fallback.
pub fn default_archive_dir() -> Result<PathBuf, ConfigError> {
    #[cfg(target_os = "linux")]
    let root = std::env::var_os("XDG_DATA_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".local/share")));
    #[cfg(target_os = "macos")]
    let root = std::env::var_os("HOME")
        .map(|home| PathBuf::from(home).join("Library/Application Support"));
    #[cfg(windows)]
    let root = std::env::var_os("LOCALAPPDATA").map(PathBuf::from);
    #[cfg(not(any(target_os = "linux", target_os = "macos", windows)))]
    let root: Option<PathBuf> = None;
    let root = root.ok_or(ConfigError::Location)?;
    if !local_path(&root) {
        return Err(ConfigError::Location);
    }
    Ok(root.join("rldyour-clipboard"))
}

/// Existing platform endpoint identity, used by explicit initialization.
pub fn default_socket_path(archive: &Path) -> Result<PathBuf, ConfigError> {
    #[cfg(target_os = "linux")]
    let root = std::env::var_os("XDG_RUNTIME_DIR")
        .map(PathBuf::from)
        .ok_or(ConfigError::Location)?;
    #[cfg(not(target_os = "linux"))]
    let root = archive.to_path_buf();
    #[cfg(target_os = "linux")]
    let _ = archive;
    if !local_path(&root) {
        return Err(ConfigError::Location);
    }
    Ok(root.join(crate::SOCKET_NAME))
}
